const PYODIDE_VERSION = "314.0.3";
const PYODIDE_BASE = `https://cdn.jsdelivr.net/pyodide/v${PYODIDE_VERSION}/full/`;
const DATA_FILES = ["experiment.csv", "experiment_missing.csv", "projectile.csv"];

let pyodide = null;
let initializing = null;

function status(message, detail = "") {
  self.postMessage({ type: "status", message, detail });
}

async function writeBundledData() {
  for (const filename of DATA_FILES) {
    const url = new URL(`../data/${filename}`, self.location.href);
    const response = await fetch(url);
    if (!response.ok) {
      throw new Error(`同梱データ ${filename} を読み込めませんでした (${response.status})`);
    }
    const bytes = new Uint8Array(await response.arrayBuffer());
    pyodide.FS.writeFile(`/home/pyodide/${filename}`, bytes);
  }
  pyodide.runPython("import os; os.chdir('/home/pyodide')");
}

async function initialize() {
  if (pyodide) return pyodide;
  if (initializing) return initializing;

  initializing = (async () => {
    status("Python実行環境を初期化しています", `Pyodide ${PYODIDE_VERSION}`);
    const { loadPyodide } = await import(`${PYODIDE_BASE}pyodide.mjs`);
    pyodide = await loadPyodide({ indexURL: PYODIDE_BASE });
    await writeBundledData();
    status("Python実行環境の準備ができました", `Python ${pyodide.runPython("import sys; sys.version.split()[0]")}`);
    self.postMessage({ type: "ready", pyodideVersion: PYODIDE_VERSION });
    return pyodide;
  })().catch((error) => {
    initializing = null;
    pyodide = null;
    throw error;
  });

  return initializing;
}

