async function runCode(message) {
  const runtime = await initialize();
  const code = String(message.code ?? "");
  const filename = String(message.filename ?? "student.py");

  if (code.length > 200_000) {
    throw new Error("コードが長すぎます。200,000文字以下にしてください。");
  }

  status("必要なPythonパッケージを確認しています");
  await runtime.loadPackagesFromImports(code);
  status("Pythonコードを実行しています");

  runtime.globals.set("__spica_student_code", code);
  runtime.globals.set("__spica_filename", filename);
  try {
    const resultText = await runtime.runPythonAsync(EXECUTION_WRAPPER, { filename: "spica_runner.py" });
    const result = JSON.parse(resultText);
    self.postMessage({ type: "result", requestId: message.requestId, result });
  } finally {
    try { runtime.globals.delete("__spica_student_code"); } catch (_) {}
    try { runtime.globals.delete("__spica_filename"); } catch (_) {}
  }
}

self.onmessage = async (event) => {
  const message = event.data ?? {};
  try {
    if (message.type === "init") {
      await initialize();
      return;
    }
    if (message.type === "run") {
      await runCode(message);
      return;
    }
    if (message.type === "ping") {
      self.postMessage({ type: "pong", ready: Boolean(pyodide), pyodideVersion: PYODIDE_VERSION });
    }
  } catch (error) {
    self.postMessage({
      type: "worker-error",
      requestId: message.requestId,
      message: error?.message || String(error),
      stack: error?.stack || "",
    });
  }
};
